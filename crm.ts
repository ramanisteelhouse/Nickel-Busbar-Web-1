import pool, { query, queryOne } from "./db.js";

const CRM_WEBHOOK_URL = process.env.CRM_WEBHOOK_URL;
const CRM_AUTH_HEADER = process.env.CRM_AUTH_HEADER || "Authorization";
const CRM_AUTH_VALUE = process.env.CRM_AUTH_VALUE;
const CRM_TIMEOUT_MS = Number(process.env.CRM_TIMEOUT_MS || 10000);
const CRM_MAX_ATTEMPTS = Number(process.env.CRM_MAX_ATTEMPTS || 6);
const CRM_RETRY_BASE_MS = Number(process.env.CRM_RETRY_BASE_MS || 60000);
const CRM_POLL_INTERVAL_MS = Number(process.env.CRM_POLL_INTERVAL_MS || 15000);
const CRM_BATCH_SIZE = Number(process.env.CRM_BATCH_SIZE || 10);

export const CRM_API_KEY = process.env.CRM_API_KEY;

/**
 * The payload contract sent to the CRM/ERP. Keep this stable - the CRM side maps
 * these fields onto its own lead record.
 */
export type CrmLead = {
  external_id: string;
  source: "website_enquiry" | "website_rfq";
  received_at: string;
  contact: {
    full_name: string | null;
    email: string | null;
    phone: string | null;
    company: string | null;
    location: string | null;
    gst_number?: string | null;
    pin_code?: string | null;
  };
  interest: {
    product_id: string | number | null;
    product_name: string | null;
    requirement: string | null;
    thickness?: string | null;
    quantity: string | null;
    message: string | null;
  };
  items?: Array<{
    product_id: string | number | null;
    product_name: string | null;
    category_name: string | null;
    quantity: number | null;
    unit_price: number | null;
    line_total: number | null;
  }>;
  totals?: {
    subtotal: number | null;
    gst: number | null;
    total: number | null;
    currency: string | null;
    items_count: number | null;
    shipping_option: string | null;
  };
  meta: {
    site_user_id: number | null;
    locale?: string | null;
    page_source?: string | null;
    user_agent?: string | null;
  };
};

type SyncRow = {
  id: number;
  external_id: string;
  payload: CrmLead;
  attempts: number;
};

const toNumber = (value: unknown): number | null => {
  if (value === null || value === undefined || value === "") return null;
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : null;
};

const toText = (value: unknown): string | null => {
  if (value === null || value === undefined) return null;
  const text = String(value).trim();
  return text || null;
};

/**
 * Creates the queue table. Follows the in-code migration pattern the rest of this
 * app uses, so a fresh deploy needs no manual SQL step.
 */
export const ensureCrmSyncSchema = async () => {
  try {
    await query(`
      CREATE TABLE IF NOT EXISTS public.crm_lead_sync (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        external_id text NOT NULL UNIQUE,
        source text NOT NULL,
        source_id bigint,
        payload jsonb NOT NULL,
        status text NOT NULL DEFAULT 'pending',
        attempts integer NOT NULL DEFAULT 0,
        last_error text,
        crm_record_id text,
        next_attempt_at timestamptz NOT NULL DEFAULT now(),
        delivered_at timestamptz,
        created_at timestamptz NOT NULL DEFAULT now(),
        updated_at timestamptz NOT NULL DEFAULT now()
      )
    `);
    await query(
      `CREATE INDEX IF NOT EXISTS crm_lead_sync_claim_idx
         ON public.crm_lead_sync (next_attempt_at) WHERE status = 'pending'`
    );
    await query(`CREATE INDEX IF NOT EXISTS crm_lead_sync_status_idx ON public.crm_lead_sync (status)`);
    await query(`CREATE INDEX IF NOT EXISTS crm_lead_sync_created_at_idx ON public.crm_lead_sync (created_at)`);
    // Lead contact details must never be readable with the browser-side publishable
    // key. No policies means deny-all; the API connects as the owner, which is exempt.
    await query(`ALTER TABLE public.crm_lead_sync ENABLE ROW LEVEL SECURITY`);
  } catch (error) {
    console.error("Failed to ensure crm_lead_sync schema is up to date", error);
  }
};

