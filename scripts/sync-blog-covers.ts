/**
 * Saves an optimised copy of every blog cover to public/img/blog-covers/<slug>.webp and writes the
 * manifest (src/lib/blogCoverLocal.ts) that tells the site which posts have one.
 *
 * Blog covers live in Supabase Storage behind signed URLs, which Google refuses to index (see
 * src/lib/blogImage.ts). The /api/blog-image proxy fixes that for any post, but a proxied image is
 * the original upload: the covers are 1000x1000 JPEGs of around 1.2MB, a quarter of a page's
 * weight, fetched through a serverless function. A local WebP of the same picture is roughly a
 * tenth of the size and is served straight from the CDN.
 *
 * The copies are the preferred source, the proxy is the fallback: a post published after the last
 * run has no copy yet, so it is served through the proxy until this is run again. Run it after
 * publishing posts or changing a cover:
 *
 *     npx tsx scripts/sync-blog-covers.ts
 *
 * It reads the published /api/blog-posts, so it needs no database credentials. With the API
 * unreachable it leaves the existing files and manifest alone rather than emptying them.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";
import sharp from "sharp";

const API_ORIGIN = (process.env.SYNC_API_ORIGIN || "https://www.nickelbusbar.com").replace(/\/+$/, "");
const OUTPUT_DIR = path.resolve(process.cwd(), "public/img/blog-covers");
const MANIFEST_PATH = path.resolve(process.cwd(), "src/lib/blogCoverLocal.ts");
// Covers are uploaded at 1000x1000 (supabase/README.md); never enlarge, never exceed 1200 wide,
// which is the width Google asks for before it will show a large image preview.
const MAX_WIDTH = 1200;
const WEBP_QUALITY = 80;
// Same ceiling the proxy applies: nothing this large is a cover photo.
const MAX_SOURCE_BYTES = 12 * 1024 * 1024;
const API_LIMIT = 50;

const OWN_ORIGIN = /^https?:\/\/(?:www\.)?nickelbusbar\.com(?=\/|$)/i;

const writeManifest = (slugs: string[]) => {
  const sorted = [...new Set(slugs)].sort();
  writeFileSync(
    MANIFEST_PATH,
    `// GENERATED by scripts/sync-blog-covers.ts — do not edit by hand.
//
// Slugs of the blog posts that have an optimised cover saved under public/img/blog-covers/.
// src/lib/blogImage.ts consults this before falling back to the /api/blog-image proxy, so a post
// listed here is served straight from the CDN as a small WebP and a post that is not is still
// served, from the proxy, until the script is run again.

export const LOCAL_BLOG_COVER_SLUGS: ReadonlySet<string> = new Set([
${sorted.map((slug) => `  ${JSON.stringify(slug)},`).join("\n")}
]);
`,
    "utf-8"
  );
};

/** Slugs listed by the previous run, so a post whose download fails today keeps its copy. */
const readPreviousManifest = (): string[] => {
  if (!existsSync(MANIFEST_PATH)) return [];
  try {
    return [...readFileSync(MANIFEST_PATH, "utf-8").matchAll(/^\s+"([^"]+)",$/gm)].map((m) => m[1]);
  } catch {
    return [];
  }
};

async function main() {
  type Row = { slug?: string; cover_image_url?: string | null };
  let rows: Row[];
  try {
    const response = await fetch(`${API_ORIGIN}/api/blog-posts?limit=${API_LIMIT}`);
    if (!response.ok) throw new Error(`API returned ${response.status}`);
    rows = (await response.json()) as Row[];
  } catch (error) {
    console.error("[blog-covers] Blog API unreachable; leaving existing copies alone.", error);
    return;
  }
  if (!Array.isArray(rows) || !rows.length) {
    console.warn("[blog-covers] API returned no posts; leaving existing copies alone.");
    return;
  }
  if (rows.length >= API_LIMIT) {
    console.warn(`[blog-covers] ${rows.length} posts is the API page size; older posts may be missing from this run.`);
  }

  mkdirSync(OUTPUT_DIR, { recursive: true });
  const kept = new Set(readPreviousManifest().filter((slug) => existsSync(path.join(OUTPUT_DIR, `${slug}.webp`))));
  const saved: string[] = [];
  const skipped: string[] = [];
  const failed: string[] = [];

  for (const row of rows) {
    const slug = row.slug?.trim();
    const source = row.cover_image_url?.trim();
    if (!slug) continue;
    // No cover, or one already on our own domain: nothing to copy.
    if (!source || !/^https?:\/\//i.test(source) || OWN_ORIGIN.test(source)) {
      skipped.push(slug);
      continue;
    }

    try {
      const response = await fetch(source, { redirect: "follow" });
      const type = (response.headers.get("content-type") || "").split(";")[0].trim().toLowerCase();
      if (!response.ok || !type.startsWith("image/")) throw new Error(`HTTP ${response.status} ${type || "(no type)"}`);
      const input = Buffer.from(await response.arrayBuffer());
      if (input.length > MAX_SOURCE_BYTES) throw new Error(`${input.length} bytes is too large`);

      const output = await sharp(input)
        .rotate() // honour EXIF orientation, then drop it
        .resize({ width: MAX_WIDTH, withoutEnlargement: true })
        .webp({ quality: WEBP_QUALITY })
        .toBuffer();
      writeFileSync(path.join(OUTPUT_DIR, `${slug}.webp`), output);
      kept.add(slug);
      saved.push(slug);
      console.log(`[blog-covers] ${slug}: ${Math.round(input.length / 1024)}KB -> ${Math.round(output.length / 1024)}KB`);
    } catch (error) {
      failed.push(slug);
      console.warn(`[blog-covers] ${slug}: could not save a copy (${error instanceof Error ? error.message : error})`);
    }
  }

  writeManifest([...kept]);
  console.log(
    `[blog-covers] ${saved.length} saved, ${skipped.length} with no copy needed, ${failed.length} failed; ` +
      `${kept.size} posts now have a local cover.`
  );
}

main().catch((error) => {
  console.error("[blog-covers] Sync failed; leaving existing copies alone.", error);
});
