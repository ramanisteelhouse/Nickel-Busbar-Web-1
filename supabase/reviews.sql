-- Customer reviews: a shareable form, a moderation gate, and display on product pages.
--
-- product_slug is nullable on purpose. A review tied to a product renders on that product page
-- and carries Review structured data; a null one is a general review of the company and renders
-- as a testimonial. Google treats reviews a business collects about itself as self-serving and
-- ineligible for rich results, so only the product-tied ones can ever earn stars — the general
-- ones are for human readers.
--
-- No foreign key to products. A product can be renamed or removed from the catalogue, and a
-- customer's review of what they bought should survive that rather than cascade away. The join
-- is by slug at read time, and a review whose product no longer exists simply stops showing on a
-- product page.
--
-- status gates publication. An open review link on a B2B site attracts spam and competitor
-- abuse, so nothing reaches the site until it is approved. Default 'pending'.
--
-- Run it in the Supabase project the site reads, fzrnezhbfyrpvudlsqny:
--   https://supabase.com/dashboard/project/fzrnezhbfyrpvudlsqny/sql/new
--
-- Safe to run twice.

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  -- Null means a general review of the company rather than of one product.
  product_slug text,
  reviewer_name text not null,
  reviewer_company text,
  -- Kept for replying and for verifying a reviewer is real. Never rendered on the site.
  reviewer_email text,
  rating smallint not null check (rating between 1 and 5),
  body text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  -- Where the link was shared, so it is possible to tell which channel actually produces
  -- reviews: 'whatsapp', 'linkedin', 'email'. Free text, set from a ?src= on the form URL.
  source text,
  created_at timestamptz not null default now(),
  approved_at timestamptz
);

comment on column public.reviews.product_slug is
  'products.slug this review is about, or null for a general company review. Deliberately not a foreign key: a review should outlive a catalogue change.';
comment on column public.reviews.status is
  'pending until approved. Only approved rows are ever served by GET /api/reviews.';

-- The read path is always "approved reviews, newest first", either for one product or for all.
create index if not exists idx_reviews_approved
  on public.reviews (status, product_slug, created_at desc);
-- The moderation queue.
create index if not exists idx_reviews_pending
  on public.reviews (status, created_at desc)
  where status = 'pending';

-- Same reasoning as supabase/rls.sql: nothing in this codebase talks to PostgREST, so enabling
-- RLS blocks the publishable key that ships in browsers while leaving the API's `postgres`
-- connection untouched. Do NOT add `force row level security` — that would subject the owner
-- connection to the policies and break every read and write the site makes.
alter table public.reviews enable row level security;
